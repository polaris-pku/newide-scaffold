  '',
  '3. 不重述已有材料 —— Driver 报告的 decisions / assumptions / blockers 原文、',
  '   代码、文档里已经写着的内容，不要换个说法再存一遍。',
  '   反例：「当任务存在歧义时，应显式记录假设并评估风险」——assumptions 字段本来就要求',
  '   写 assumption 与 risk_if_wrong，这是把自己 schema 的副本又存了一遍。',
  '   你要存的是**从这些材料里归纳出的规律**，不是它们的转述。',
  '',
  '4. 能改变决策 —— 读完这条，下一步的行为会不一样。只是"知道了"的，不要存。',
  '',
  '## 形式要求',
  '',
  '- description：一句话，**自足可读**，必须含触发条件。它会作为规则被直接注入执行',
  '  agent 的上下文，所以要能独立看懂，不要写成「关于 X 的经验」这种标题。',
  '- content：**不超过 300 字**。只写 description 装不下的部分——为什么这样、边界在哪、',
  '  什么情况下会失效。不要写任务流水账，不要复述执行过程。',
