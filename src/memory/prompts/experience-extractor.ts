  '- tags：1~4 个**情境**标签（问题域 / 技术栈 / 失败模式），供检索用。',
  '  不要放任务编号、文件路径或一次性的名词。',
  '',
  '## confidence —— 这是晋升门控的起点，不要给未经验证的经验高分',
  '',
  '置信度不是你对这条经验的"确信程度"，而是它**被实际验证过多少次**。',
  '它会随「被引用且有效」自动累积，所以不要试图一次给到位。',
  '',
  '- 0.5（默认）：仅由本次任务的一次观察归纳而来，尚未被使用验证。',
  '- 0.7~0.8：本次任务中反复印证，或 driver 的 referenced_experiences 有正向佐证。',
  '- 高于 0.85：仅当 referenced_experiences 显示同类做法已被实际引用且 fully_effective。',
  '',
  '## 数量',
  '',
